// A browsing-only catalog. These entries are not executable modules and must
// never be added to GamejamRequest or to generated task instructions.
export type GameFeature = {
  id: string;
  name: string;
  category: string;
  group: string;
  description: string;
  keywords: string;
};
export type FeatureCategory = {
  id: string;
  name: string;
  groups: { id: string; name: string; features: GameFeature[] }[];
};
type GroupSource = [id: string, name: string, examples: string[]];
const category = (
  id: string,
  name: string,
  aliases: string,
  groups: GroupSource[],
): FeatureCategory => ({
  id,
  name,
  groups: groups.map(([groupId, groupName, examples]) => ({
    id: `${id}.${groupId}`,
    name: groupName,
    features: examples.map((featureName) => ({
      id: `${id}.${groupId}.${featureName}`,
      name: featureName,
      category: name,
      group: groupName,
      description: `${name}의 ${groupName}에 활용할 수 있는 ${featureName} 기능 예시입니다.`,
      keywords: `${name} ${groupName} ${featureName} ${aliases}`,
    })),
  })),
});

