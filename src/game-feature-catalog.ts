export const GAME_FEATURES = GAME_FEATURE_CATALOG.flatMap((item) =>
  item.groups.flatMap((group) => group.features),
);

export function searchGameFeatures(query: string) {
  const words = query
    .normalize('NFKC')
    .toLocaleLowerCase()
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  return GAME_FEATURES.filter((feature) => {
    const text = `${feature.keywords} ${feature.description}`
      .normalize('NFKC')
      .toLocaleLowerCase();
    return words.every((word) => text.includes(word));
  });
}

